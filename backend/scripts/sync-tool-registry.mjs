/**
 * Copies the proxy's generated `tessera.tools/v3` registry (`docs/tool-registry.json` in the proxy repository) into
 * `src/contracts/tools/v3/tool-registry.document.ts`. The registry is a versioned wire artifact: the dashboard keeps
 * a copy instead of importing proxy code. Run after the proxy changes its tools:
 *
 *   node scripts/sync-tool-registry.mjs [path/to/tool-registry.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXPECTED_VERSION = 'tessera.tools/v3';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(
  process.argv[2] ??
    resolve(root, '..', '..', 'backend', 'docs', 'tool-registry.json'),
);
const target = resolve(
  root,
  'src',
  'contracts',
  'tools',
  'v3',
  'tool-registry.document.ts',
);

const document = JSON.parse(readFileSync(source, 'utf8'));
if (document.registryVersion !== EXPECTED_VERSION) {
  throw new Error(
    `${source} is ${document.registryVersion}, expected ${EXPECTED_VERSION}`,
  );
}
if (!Array.isArray(document.tools) || document.tools.length === 0) {
  throw new Error(`${source} lists no tools`);
}
const ids = new Set();
for (const tool of document.tools) {
  if (!/^[a-z][a-z0-9_]{0,63}$/.test(tool.id) || ids.has(tool.id))
    throw new Error(`Bad or duplicate tool id: ${tool.id}`);
  if (!['field', 'file', 'full'].includes(tool.contextType))
    throw new Error(`${tool.id}: bad contextType`);
  if (!tool.config || typeof tool.config !== 'object')
    throw new Error(`${tool.id}: missing config schema`);
  ids.add(tool.id);
}

writeFileSync(
  target,
  `// Generated by scripts/sync-tool-registry.mjs from the proxy's docs/tool-registry.json. Do not edit.
import type { ToolRegistryDocumentV3 } from './tool-registry.types.js';

export const TOOL_REGISTRY_V3_DOCUMENT: ToolRegistryDocumentV3 = ${JSON.stringify(document, null, 2)};
`,
);
console.log(
  `Wrote ${document.tools.length} tools (${document.registryVersion}) to ${target}`,
);
